# 讀取測試案例的總數量
n = int(input())

# 使用 range(1, n + 1) 讓迴圈變數 i 從 1 開始，方便最後印出 Case 編號
for i in range(1, n + 1):
    # 讀取起點 (x1, y1) 和終點 (x2, y2) 的座標
    x1, y1, x2, y2 = map(int, input().split())
    
    # 【步驟 1：確認點在哪一條斜線上】
    # 斜線的編號 = x 座標 + y 座標
    a = x1 + y1  # 起點所在的斜線編號
    b = x2 + y2  # 終點所在的斜線編號

    # 【步驟 2：計算從原點 (0,0) 走到該點的「總步數」】
    # 總步數 = (抵達該斜線前累積的步數) + (在該斜線上多走的步數)
    # 1. 抵達前累積步數：利用等差數列公式 梯形面積 = (上底+下底)*高/2，寫成 a * (a + 1) // 2
    # 2. 斜線上多走步數：沿箭頭每走一步 x 就加 1，所以加上 x 座標即可
    s1 = (a * (a + 1) // 2) + x1  # 原點走到起點的總步數
    s2 = (b * (b + 1) // 2) + x2  # 原點走到終點的總步數
    
    # 【步驟 3：計算兩點之間的相對距離】
    # 題目保證一定能從起點走到終點，所以直接用終點步數扣掉起點步數
    ans = s2 - s1
    
    # 依照題目要求的格式輸出結果
    print(f"Case {i}: {ans}")